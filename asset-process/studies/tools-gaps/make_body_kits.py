"""Write author-pack/labels/body-kits.json: the body kits of the standard male figure the harness draws, and test it.

usage: make_body_kits.py            (writes the JSON, then rebuilds every slot from the JSON and draws it)

Which kits: asked of the client itself, `asset_pose.exe CACHE info kits` (Appearance::standard: for each body part
the lowest-numbered enabled kit of the gender; the harness then sets colours [3, 2, 3, 1, 0]). Each kit here is a
single model, used as stored (identity_kit.rs Kit::mesh: one model is not re-combined; the kit's own recolours,
none for these seven, are applied). Meshes are decoded with tools/osrscache.py and checked against the counts and
label histograms the client prints.
Test: for every slot a model is re-encoded FROM THE JSON (author.native_codec.model; labels, priorities, colours
kept) and worn as model:PATH@SLOT; pose.py --diff against the bare figure must be 0 in the bind pose and walk frames.
"""
import os as _ap_os, sys as _ap_sys  # find asset_paths.py (see SETUP.md)
_ap_d = _ap_os.path.dirname(_ap_os.path.abspath(globals().get('__file__') or 'x'))
while not _ap_os.path.isfile(_ap_os.path.join(_ap_d, 'asset_paths.py')) and _ap_os.path.dirname(_ap_d) != _ap_d: _ap_d = _ap_os.path.dirname(_ap_d)
_ap_sys.path.append(_ap_d); import asset_paths as _AP  # noqa: E402
import sys, json, re, subprocess, pathlib, collections, ast
T = pathlib.Path(_AP.fix(r'<ROOT>\tools'))
sys.path.insert(0, str(T))
import osrscache, author
EXE = _AP.fix(r'<CLIENT_BIN>\asset_pose.exe')
PY = [_AP.fix(r'<PYTHON>'), '-I']
DST = pathlib.Path(_AP.fix(r'<ROOT>\author-pack\labels\body-kits.json'))
OUT = pathlib.Path(__file__).parent / 't5'; OUT.mkdir(exist_ok=True)

info = subprocess.run([EXE, str(osrscache.CACHE), 'info', 'kits'], capture_output=True, text=True, check=True).stdout
head = re.search(r'standard figure: gender (\d+) colors (\[.*?\]) equipment (\[.*?\])', info)
player_recolours = [[int(a), int(b)] for a, b in re.findall(r'player_recolor part=\d+ from=(\d+) to=(\d+)', info)]
hist = lambda v: {str(k): n for k, n in sorted(collections.Counter(v).items())}
slots = {}
blocks = re.split(r'(?m)^(?=kit slot=)', info)[1:]
for b in blocks:
    m = re.match(r'kit slot=(\d+) name=(\w+) part=(\d+) id=(\d+) models=(\[.*?\]) recolor=(\[.*?\]) retexture=(\[.*?\]) vertices=(\d+) faces=(\d+)', b)
    slot, name, part, kit_id, nv, nf = int(m[1]), m[2], int(m[3]), int(m[4]), int(m[8]), int(m[9])
    model_ids = ast.literal_eval(m[5]); recolor = ast.literal_eval(m[6]); retexture = ast.literal_eval(m[7])
    assert len(model_ids) == 1 and not retexture, 'a kit of several models would need Model::combine; not needed for the standard figure'
    g = osrscache.model(model_ids[0])
    colours = list(g['colors'])
    for a, c in recolor: colours = [c if x == a else x for x in colours]
    assert (len(g['vertices']), len(g['faces'])) == (nv, nf), (name, len(g['vertices']), nv)
    client_labels = ast.literal_eval(re.search(r'vertex labels (\{.*?\})', b)[1])
    assert dict(collections.Counter(g['vertex_skins'])) == client_labels, name
    assert all(t == -1 for t in g['face_textures']), name
    drawn = list(colours)
    for a, c in player_recolours: drawn = [c if x == a else x for x in drawn]
    V = [[x, -y, z] for x, y, z in g['vertices']]
    e = dict(slot=slot, slot_name=name, body_part=part, kit_id=kit_id, model_ids=model_ids, source_format=g['format'],
             vertex_count=nv, face_count=nf,
             bounds_min=[min(p[i] for p in V) for i in range(3)], bounds_max=[max(p[i] for p in V) for i in range(3)],
             vertex_label_histogram=hist(g['vertex_skins']), face_label_histogram=hist(g['face_skins']),
             face_priority_histogram=hist(g['priorities']),
             vertices=V, vertex_labels=list(g['vertex_skins']),
             faces=[list(f) for f in g['faces']], face_labels=list(g['face_skins']), face_priorities=list(g['priorities']),
             face_colours=colours, face_colours_hsl=[list(osrscache.hsl_split(c)) for c in colours],
             face_colours_drawn=drawn, face_colours_drawn_hsl=[list(osrscache.hsl_split(c)) for c in drawn])
    if any(g['render_types']): e['face_flat'] = [1 if r == 1 else 0 for r in g['render_types']]
    if any(g['alpha']): e['face_alpha'] = list(g['alpha'])
    if any(g['depth_bias']): e['face_depth_offsets'] = list(g['depth_bias'])
    slots[name] = e
doc = dict(
    about=('Body kits of the standard male figure that tools/pose.py and tools/figure.py draw (the bare figure, entry `none`). '
           'Private: derived from the game cache. Generated by studies/tools-gaps/make_body_kits.py; do not edit by hand.'),
    coordinates=('Worn space. vertices are [x, height, z] in game units: height is UP (minus the cache y), feet at 0, crown near 196; '
                 "the character's RIGHT side is negative x; its FRONT is negative z. To write a model: cache vertex = [x, -height, z], faces unchanged."),
    figure=dict(gender=int(head[1]), colours=ast.literal_eval(head[2]), equipment=ast.literal_eval(head[3]),
                equipment_note='twelve slot values: 0 = empty, kit id + 256 = body kit',
                player_recolours=player_recolours,
                player_recolours_note=('[from, to] pairs the figure applies to the WHOLE assembled mesh, a model worn in a slot included: '
                                       '6798 hair, 8741 torso (9104 its trim), 25238 legs, 4626 feet, 4550 skin. face_colours are the kit\'s own values '
                                       '(use them in a model that should take the figure\'s colours); face_colours_drawn are what this figure shows.')),
    fields=dict(model_ids='cache models (index 7) of the kit; one each here, used as stored',
                vertices='[x, height, z] per vertex', vertex_labels='animation label per vertex (LABELS.md)',
                faces='[a, b, c] vertex indices, winding as stored (cache coordinates, y down)',
                face_labels='per face (used only by fading sequences)', face_priorities='per face draw priority (decides layering on a player)',
                face_colours='16-bit HSL per face before the player recolours; hue = v >> 10, saturation = (v >> 7) & 7, lightness = v & 127',
                face_flat='present only when the kit has flat-shaded faces (1 = flat)', face_alpha='present only when any face is translucent',
                face_depth_offsets='present only when any face carries one'),
    slot_order=['hair', 'jaw', 'body', 'arms', 'hands', 'legs', 'feet'],
    slots=slots)
DST.write_text(json.dumps(doc, separators=(',', ':')).replace('"slots":{', '"slots":{\n').replace('},"', '},\n"'), encoding='utf-8', newline='\n')
print(f'wrote {DST} ({DST.stat().st_size} bytes)')
for n, e in slots.items():
    print(f'  {n:5s} slot {e["slot"]:2d} kit {e["kit_id"]:2d} models {e["model_ids"]}: {e["vertex_count"]} vertices {e["face_count"]} faces, '
          f'box {e["bounds_min"]}..{e["bounds_max"]}, labels {e["vertex_label_histogram"]}, priorities {e["face_priority_histogram"]}'
          + (', has flat faces' if 'face_flat' in e else '') + (', has alpha' if 'face_alpha' in e else ''))

# ---- test: rebuild every slot from the JSON alone and draw it in place of the kit ------------------------------
J = json.loads(DST.read_text(encoding='utf-8'))
ok = True
for n in J['slot_order']:
    e = J['slots'][n]
    g = dict(vertices=[[x, -h, z] for x, h, z in e['vertices']], faces=[tuple(f) for f in e['faces']], colors=e['face_colours'],
             vertex_skins=e['vertex_labels'], face_skins=e['face_labels'], priorities=e['face_priorities'])
    if 'face_flat' in e: g['render_types'] = e['face_flat']
    if 'face_alpha' in e: g['alpha'] = e['face_alpha']
    if 'face_depth_offsets' in e: g['face_flags'] = [(b // 2) & 255 for b in e['face_depth_offsets']]
    path = OUT / f'kit-{n}.bin'; path.write_bytes(author.native_codec.model(g))
    for extra, tag in (([], 'front'), (['--yaw', '1216'], 'back')):
        r = subprocess.run([*PY, str(T / 'pose.py'), str(OUT / f'kit-{n}-{tag}.png'), f'none,model:{path.as_posix()}@{n}',
                            '--seq', '819', '--frames', 'bind,0,1,2,3,4,5,6,7', '--diff', '1:2', *extra], capture_output=True, text=True)
        if r.returncode: raise SystemExit(r.stdout + r.stderr)
        counts = [int(x) for x in re.findall(r': (\d+) of \d+ pixels differ', r.stdout)]
        assert len(counts) == 9
        ok &= not any(counts)
        print(f'  rebuilt {n} worn as model:kit-{n}.bin@{n} against the bare figure, {tag} view, bind + walk 0..7: differing pixels {counts}')
print('ALL ZERO' if ok else 'DIFFERENCES FOUND')
